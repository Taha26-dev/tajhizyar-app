/// پیام‌های استاندارد فارسی خطا — منبع واحد نمایش خطا در کل اپلیکیشن.
///
/// نگاشت خطاهای شبکه/سرور به این پیام‌ها یک‌جا و در لایه شبکه
/// ([ApiClient] و [ApiException]) انجام می‌شود؛ صفحات فقط
/// [ApiException.message] یا helper سراسری [apiErrorMessage] را
/// نمایش می‌دهند و نباید پیام خطای شبکه را دوباره بسازند.
///
/// مزایا:
/// - متن یکسان و درست برای هر خطا در همه صفحات
/// - تغییر متن‌ها فقط در همین فایل (بدون جستجوی کل پروژه)
/// - دسته‌بندی خطا ([ApiErrorKind]) و متن آن همیشه هماهنگ‌اند
abstract final class ErrorMessages {
  ErrorMessages._();

  // ─────────── دسته‌های استاندارد خطا ───────────

  /// قطع اینترنت / عدم دسترسی به سرور
  static const String networkOffline =
      'ارتباط با سرور برقرار نشد؛ لطفاً اتصال اینترنت خود را بررسی کنید.';

  /// مهلت دریافت پاسخ سرور به پایان رسید
  static const String timeout =
      'زمان دریافت اطلاعات به پایان رسید؛ لطفاً دوباره تلاش کنید.';

  /// مهلت آپلود فایل (تصویر) به پایان رسید
  static const String uploadTimeout =
      'زمان آپلود به پایان رسید؛ اتصال اینترنت را بررسی و دوباره تلاش کنید.';

  /// خطای سرور (کدهای ۵xx و پاسخ‌های ناموفق بدون توضیح)
  static const String serverError =
      'خطای سرور رخ داده است؛ لطفاً بعداً دوباره تلاش کنید.';

  /// نشست نامعتبر (کد ۴۰۱) — همراه با خروج خودکار از حساب و
  /// هدایت به صفحه ورود فروشنده. در سیستم جدید توکن ۳۰ روزه با فعالیت
  /// تمدید می‌شود؛ ۴۰۱ یعنی توکن «منقضی» شده یا «باطل» شده است
  /// (مثلاً با خروج از همه دستگاه‌ها در دستگاهی دیگر).
  static const String sessionExpired =
      'نشست شما پایان یافته یا منقضی شده است؛ لطفاً دوباره وارد شوید.';

  /// مورد درخواستی یافت نشد (کد ۴۰۴)
  static const String notFound =
      'اطلاعات موردنظر یافت نشد؛ ممکن است حذف شده یا در دسترس نباشد.';

  /// خطای ناشناخته — هر خطایی که از سرور یا شبکه تعریف‌شده نیست
  /// (مثل خطای پردازش پاسخ).
  static const String unknown =
      'خطای ناشناخته‌ای رخ داد؛ لطفاً دوباره تلاش کنید.';

  // ─────────── پیام‌های مکمل متداول شبکه ───────────

  /// درخواست به هر دلیلی انجام نشد (بدنه بدون پیام مشخص)
  static const String requestFailed =
      'درخواست انجام نشد؛ لطفاً دوباره تلاش کنید.';

  /// دریافت اطلاعات از سرور ناموفق بود (`success == false` بدون پیام)
  static const String fetchFailed =
      'دریافت اطلاعات از سرور ناموفق بود؛ لطفاً دوباره تلاش کنید.';

  /// پاسخ سرور ساختار موردانتظار را نداشت (مثل نبود توکن در پاسخ ورود)
  static const String badResponse =
      'پاسخ سرور معتبر نیست؛ لطفاً دوباره تلاش کنید.';

  // ─────────── برچسب‌های مشترک ───────────

  /// برچسب دکمه تلاش مجدد — یک‌جا تعریف شده تا در همه صفحات یکسان باشد.
  static const String retry = 'تلاش مجدد';
}
